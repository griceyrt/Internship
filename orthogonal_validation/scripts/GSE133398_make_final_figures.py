# =============================================================================
# FIGURE 1 — DE volcano, gene level
# =============================================================================
print("\n=== Figure 1: DE volcano, gene level ===")
de = pd.read_csv(os.path.join(BASE, "results", "normalisation_GSE133398", "deseq2_KO_vs_WT.tsv"),
                  sep="\t", index_col=0)
de.index.name = "gene_id"
de = de.dropna(subset=["log2FoldChange", "padj"])
de = de[de["padj"] > 0]
de["gene_name"] = de.index.map(gene_map)
de["neg_log10_padj"] = -np.log10(de["padj"])
de["category"] = "ns"
de.loc[(de.log2FoldChange > 0.5) & (de.padj < 0.05), "category"] = "up"
de.loc[(de.log2FoldChange < -0.5) & (de.padj < 0.05), "category"] = "down"

fig, ax = plt.subplots(figsize=(4.6, 4.2))
ns_mask = de["category"] == "ns"
ax.scatter(de.loc[ns_mask, "log2FoldChange"], de.loc[ns_mask, "neg_log10_padj"],
           c="#CCCCCC", s=3, alpha=0.3, linewidths=0, zorder=1, rasterized=True)
up_mask = de["category"] == "up"
ax.scatter(de.loc[up_mask, "log2FoldChange"], de.loc[up_mask, "neg_log10_padj"],
           c="#D55E00", s=10, alpha=0.85, linewidths=0, zorder=2)
dn_mask = de["category"] == "down"
ax.scatter(de.loc[dn_mask, "log2FoldChange"], de.loc[dn_mask, "neg_log10_padj"],
           c="#0072B2", s=10, alpha=0.85, linewidths=0, zorder=2)
ax.axvline(0.5, color="#BBBBBB", ls="--", lw=0.7)
ax.axvline(-0.5, color="#BBBBBB", ls="--", lw=0.7)
ax.axhline(-np.log10(0.05), color="#BBBBBB", ls="--", lw=0.7)
top_sig = de[de.category != "ns"].dropna(subset=["gene_name"]).sort_values("padj").head(15)
texts = []
for gid, row in top_sig.iterrows():
    col = "#D55E00" if row.category == "up" else "#0072B2"
    ax.scatter(row.log2FoldChange, row.neg_log10_padj, c=col, s=25, zorder=5, edgecolors="black", linewidths=0.5)
    texts.append(ax.text(row.log2FoldChange, row.neg_log10_padj, row.gene_name, fontsize=6, fontstyle="italic"))
ax.set_ylim(0, de["neg_log10_padj"].max() * 1.12)
adjust_text(texts, ax=ax, **ADJ)
ax.set_xlabel("log₂FC (SRSF3-KO / WT)")
ax.set_ylabel("−log₁₀(padj)")
save_both(fig, "GSE133398_DE_volcano_gene_level")
print(f"  Significant: {(de.category != 'ns').sum()} "
      f"(up={(de.category == 'up').sum()}, down={(de.category == 'down').sum()})")

# =============================================================================
# FIGURE 2 — DE volcano, transcript level (stageR two-stage)
# =============================================================================
print("\n=== Figure 2: DE volcano, transcript level ===")
deb = pd.read_csv(os.path.join(BASE, "results", "normalisation_GSE133398_stageR", "deseq2_stageR_KO_vs_WT.tsv"),
                   sep="\t")
deb = deb.dropna(subset=["log2FoldChange", "padj_gene_stageR"])
deb = deb[deb["padj_gene_stageR"] >= 0]
de_gene = (deb.assign(abslfc=deb["log2FoldChange"].abs())
              .sort_values(["padj_gene_stageR", "abslfc"], ascending=[True, False])
              .drop_duplicates("gene_id").set_index("gene_id"))
de_gene["category"] = "ns"
de_gene.loc[(de_gene.log2FoldChange > 0.5) & (de_gene.padj_gene_stageR < 0.05), "category"] = "up"
de_gene.loc[(de_gene.log2FoldChange < -0.5) & (de_gene.padj_gene_stageR < 0.05), "category"] = "down"

# a handful of genes get an exact-zero padj from stageR (true zero, not just very
# small) -- -log10(0) is infinite, so place those at a fixed ceiling just above
# the highest real value and mark them with a triangle, rather than letting an
# arbitrary percentile cap squash dozens of legitimately-spread-out genes together
true_max_nlp = (-np.log10(de_gene.loc[de_gene.padj_gene_stageR > 0, "padj_gene_stageR"])).max()
ZERO_CEILING = true_max_nlp + 1.0
de_gene["neg_log10_padj"] = np.where(de_gene["padj_gene_stageR"] > 0,
                                      -np.log10(de_gene["padj_gene_stageR"]), ZERO_CEILING)
de_gene["y_plot"] = de_gene["neg_log10_padj"]
de_gene["clipped"] = de_gene["padj_gene_stageR"] == 0

fig, ax = plt.subplots(figsize=(4.6, 4.2))
ns_mask = de_gene["category"] == "ns"
ax.scatter(de_gene.loc[ns_mask, "log2FoldChange"], de_gene.loc[ns_mask, "y_plot"],
           c="#CCCCCC", s=3, alpha=0.3, linewidths=0, zorder=1, rasterized=True)
up_mask = (de_gene["category"] == "up") & ~de_gene["clipped"]
ax.scatter(de_gene.loc[up_mask, "log2FoldChange"], de_gene.loc[up_mask, "y_plot"],
           c="#D55E00", s=10, alpha=0.85, linewidths=0, zorder=2)
up_clip = (de_gene["category"] == "up") & de_gene["clipped"]
if up_clip.any():
    ax.scatter(de_gene.loc[up_clip, "log2FoldChange"], de_gene.loc[up_clip, "y_plot"],
               c="#D55E00", s=14, alpha=0.85, marker="^", linewidths=0, zorder=3)
dn_mask = (de_gene["category"] == "down") & ~de_gene["clipped"]
ax.scatter(de_gene.loc[dn_mask, "log2FoldChange"], de_gene.loc[dn_mask, "y_plot"],
           c="#0072B2", s=10, alpha=0.85, linewidths=0, zorder=2)
dn_clip = (de_gene["category"] == "down") & de_gene["clipped"]
if dn_clip.any():
    ax.scatter(de_gene.loc[dn_clip, "log2FoldChange"], de_gene.loc[dn_clip, "y_plot"],
               c="#0072B2", s=14, alpha=0.85, marker="^", linewidths=0, zorder=3)
ax.axvline(0.5, color="#BBBBBB", ls="--", lw=0.7)
ax.axvline(-0.5, color="#BBBBBB", ls="--", lw=0.7)
ax.axhline(-np.log10(0.05), color="#BBBBBB", ls="--", lw=0.7)
sig_named = de_gene[(de_gene.category != "ns") & (de_gene["gene_name"] != "unannotated")]
# label by log2FC extremes (not padj rank) -- many genes tie at padj=0, so a
# padj-based label pick clusters them all at the same height; picking by fold
# change instead gives natural spread across the x-axis
top_up = sig_named[sig_named.category == "up"].nlargest(6, "log2FoldChange")
top_dn = sig_named[sig_named.category == "down"].nsmallest(6, "log2FoldChange")
top_sig = pd.concat([top_up, top_dn])
texts = []
for gid, row in top_sig.iterrows():
    col = "#D55E00" if row.category == "up" else "#0072B2"
    ax.scatter(row.log2FoldChange, row.y_plot, c=col, s=25, zorder=5, edgecolors="black", linewidths=0.5)
    texts.append(ax.text(row.log2FoldChange, row.y_plot, row.gene_name, fontsize=6, fontstyle="italic"))
ax.set_ylim(0, ZERO_CEILING + 2.4)
adjust_text(texts, ax=ax, **ADJ)
ax.set_xlabel("log₂FC (SRSF3-KO / WT)")
ax.set_ylabel("−log₁₀(padj)")  # deliberately NOT "...stageR gene" -- keep jargon off the axis
save_both(fig, "GSE133398_DE_volcano_transcript_level")
n_sig_genes = (de_gene.category != "ns").sum()
n_sig_tx = ((deb.padj_tx_stageR.notna()) & (deb.padj_tx_stageR < 0.05)).sum()
print(f"  Significant genes (stage 1): {n_sig_genes}; significant transcripts (stage 2): {n_sig_tx}")

