only_srsf3 = len(srsf3_de_b_genes - nan_de_genes)
both = len(nan_de_genes & srsf3_de_b_genes)
make_pie((only_nan, only_srsf3, both), "Nanopore", "SRSF3-KO", "GSE133398_DE_overlap_Nanopore_transcript_level")
print(f"  Transcript level: Nanopore only={only_nan}, SRSF3-KO only={only_srsf3}, both={both}")

# =============================================================================
# FIGURE 6 — splicing overlap with Nanopore
# =============================================================================
print("\n=== Figure 6: splicing overlap pie ===")
only_nan = len(nan_splice_genes - srsf3_splice_genes)
only_srsf3 = len(srsf3_splice_genes - nan_splice_genes)
both = len(nan_splice_genes & srsf3_splice_genes)
make_pie((only_nan, only_srsf3, both), "Nanopore", "SRSF3-KO", "GSE133398_splicing_overlap_Nanopore")
