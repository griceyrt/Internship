# FIGURE 3 — splicing dPSI volcano (KEEPS an in-plot legend: event type = count)
# =============================================================================
print("\n=== Figure 3: splicing dPSI volcano ===")
dpsi = load_suppa_dir(SUPPA_DIR, "diff_*_strict.dpsi.temp.0")
dpsi["dPSI"] = -dpsi["dPSI"]  # file is WT-KO -> negate to KO-WT, project convention
dpsi["neg_log10_p"] = -np.log10(dpsi["pval"])
dpsi["sig"] = (dpsi["dPSI"].abs() > 0.1) & (dpsi["pval"] < 0.05)

EVENT_COLORS = {"A3": "#E69F00", "A5": "#56B4E9", "AF": "#009E73", "AL": "#F0E442",
                "MX": "#0072B2", "RI": "#D55E00", "SE": "#CC79A7"}
counts = dpsi[dpsi["sig"]]["event_type"].value_counts()

fig, ax = plt.subplots(figsize=(5.2, 3.8))
ns = dpsi[~dpsi["sig"]]
ax.scatter(ns["dPSI"], ns["neg_log10_p"], c="#CCCCCC", s=4, alpha=0.4, linewidths=0, zorder=1, rasterized=True)
for etype in counts.sort_values(ascending=False).index:
    sub = dpsi[dpsi["sig"] & (dpsi["event_type"] == etype)]
    ax.scatter(sub["dPSI"], sub["neg_log10_p"], c=EVENT_COLORS[etype], s=14, alpha=0.9,
               linewidths=0, zorder=2, label=f"{etype} = {counts[etype]}")
ax.axvline(0.1, color="#BBBBBB", ls="--", lw=0.7)
ax.axvline(-0.1, color="#BBBBBB", ls="--", lw=0.7)
ax.axhline(-np.log10(0.05), color="#BBBBBB", ls="--", lw=0.7)
ax.set_xlabel("dPSI (SRSF3-KO − WT)")
ax.set_ylabel("−log₁₀(p)")
ax.legend(frameon=False, fontsize=6.5, loc="upper left", bbox_to_anchor=(1.02, 1.0),
          markerscale=1.3, handletextpad=0.5, borderaxespad=0)
save_both(fig, "GSE133398_splicing_dPSI_volcano")
print(f"  Significant events: {dpsi['sig'].sum()} / {len(dpsi)}. Breakdown: {dict(counts)}")

