"""
GSE133398 (SRSF3-KO hepatocytes, Nick Webster lab) — final publication-style figures
for the reviewer rebuttal.

Produces 6 figures (SVG + PNG each), no in-figure titles, no internal jargon
("Option A/B", "stageR") — matches the style of Chikhaoui_Mamgain_MS.pdf's own
figures (descriptive text lives in the companion figure_legends.txt, not on the
plot itself). The splicing volcano is the one exception: it keeps an in-plot
legend (event type = count) since a 7-color scatter needs an on-plot key to be
readable standalone.

Inputs required (all produced earlier in the pipeline):
  - results/normalisation_GSE133398/deseq2_KO_vs_WT.tsv            (gene-level DESeq2)
  - results/normalisation_GSE133398_stageR/deseq2_stageR_KO_vs_WT.tsv  (transcript-level + stageR)
  - results/suppa_GSE133398_2026-07-13/diff/diff_<TYPE>_strict.dpsi.temp.0  (7 files, SRSF3-KO splicing)
  - data/nanopore_suppa/res_<TYPE>.dpsi.temp.0                      (7 files, Nanopore splicing)
  - data/Table3-differential_expressiong_WTvsPerKO.xlsx             (Nanopore DE, perKO_sig sheet)
  - boundary_analysis/data/transcriptome_productivity.gtf           (gene_id -> gene_name map)

Output: results/figures_GSE133398/ (overwrites in place) + figure_legends.txt is
maintained separately (not regenerated by this script — edit by hand if numbers change).

Run from: orthogonal_validation/
    python3 scripts/GSE133398_make_final_figures.py
"""

