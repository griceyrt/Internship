ADJ = dict(expand=(2.8, 3.2), force_text=(1.8, 2.8), force_points=(1.3, 1.3),
           arrowprops=dict(arrowstyle="-", color="#888888", lw=0.5, shrinkA=3, shrinkB=3))


def build_gene_map(gtf_path):
    gmap = {}
    with open(gtf_path) as fh:
        for line in fh:
            if "\tgene\t" not in line:
                continue
            gid = re.search(r'gene_id "([^"]+)"', line)
            gname = re.search(r'gene_name "([^"]+)"', line)
            if gid and gname:
                gmap[gid.group(1)] = gname.group(1)
    return gmap


def save_both(fig, name):
    for ext in ["svg", "png"]:
        fig.savefig(os.path.join(OUT, f"{name}.{ext}"), format=ext, bbox_inches="tight",
                    dpi=300 if ext == "png" else None)
    plt.close(fig)
    print(f"  Saved: {name}.svg / .png")


def load_suppa_dir(dirpath, pattern):
    dfs = []
    for f in sorted(glob.glob(os.path.join(dirpath, pattern))):
        base = os.path.basename(f)
        etype = re.sub(r"^(diff_|res_)", "", base)
        etype = re.sub(r"(_strict)?\.dpsi\.temp\.0$", "", etype)
        df = pd.read_csv(f, sep="\t", index_col=0, header=0)
        df.columns = ["dPSI", "pval"]
        df["event_type"] = etype
        df = df.dropna().query("pval > 0")
        dfs.append(df)
    return pd.concat(dfs)


def make_pie(counts, labelA, labelB, path):
    """counts = (only_a, only_b, both). 'Both' gets a short manual leader line
    close to its wedge (no title to dodge anymore, so no need to route it far away)."""
    only_a, only_b, both = counts
    total = only_a + only_b + both
    sizes = [only_a, only_b, both]
    labels = [f"{labelA} only\n({only_a}, {only_a/total*100:.0f}%)",
              f"{labelB} only\n({only_b}, {only_b/total*100:.0f}%)", ""]
    colors = ["#56B4E9", "#009E73", "#E69F00"]
    fig, ax = plt.subplots(figsize=(4.3, 4.3))
    wedges, texts = ax.pie(sizes, labels=labels, colors=colors, startangle=90,
                            labeldistance=1.12, textprops=dict(fontsize=8.5),
                            wedgeprops=dict(edgecolor="white", linewidth=1))
    both_wedge = wedges[2]
    theta = np.deg2rad((both_wedge.theta1 + both_wedge.theta2) / 2)
    x, y = np.cos(theta), np.sin(theta)
    tx, ty = 1.05 + 0.55 * np.cos(theta), y + 0.48
    ha = "left" if x >= 0 else "right"
    ax.annotate(f"Both\n({both}, {both/total*100:.2g}%)", xy=(x, y), xytext=(tx, ty),
                fontsize=8.5, ha=ha, va="bottom",
                arrowprops=dict(arrowstyle="-", color="#888888", lw=0.7, shrinkA=2, shrinkB=2))
    save_both(fig, path)


